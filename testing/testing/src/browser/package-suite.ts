/**
 * A package's own browser suite (COR-2080, COR-2092): the `browser/` directory of a component
 * package, with its application fixtures in `fixtures/` (declared in `fixture-declarations.ts`),
 * its specs in `tests/`, its baselines in `snapshots/` and its `playwright.config.ts`. Everything
 * generated goes to `browser/.playwright/`, which Git ignores.
 *
 * Every package's suite serves the same fixture page, the one the root suite served before
 * COR-2092: every Cinder, chat, editor and terminal fixture, mounted by Cinder core's host
 * (`<core>/browser/host.ts`). The page's stylesheets are part of what a baseline records, and which
 * stylesheets a page loads, and in what order, follows from every module it imports, so a page
 * that serves one package's fixtures alone renders differently (COR-2080's terminal baselines). A
 * suite runs its own specs, and its component sweep covers only the fixtures it owns
 * (`owned-slugs.json`).
 */
export type PackageSuiteOptions = {
  /** The package's `browser/` directory. */
  root: string;
  /** Directories scanned for `*-fixtures.ts` declarations and `*.fixture.svelte` hosts. */
  fixtureRoots: string[];
  /** The directories of application fixtures (`*.svelte`). */
  appFixtureRoots: string[];
  /** The application fixtures every suite serves, by component name. */
  appFixtureDeclarations: Readonly<Record<string, readonly string[]>>;
  /** The module whose default export is the host's options (`FixtureHostOptions` but `modules`). */
  host: string;
  /** The fixture roots, among `fixtureRoots`, whose fixtures this package owns. */
  ownFixtureRoots: string[];
  /** The application fixtures, among the declared ones, this package owns. */
  ownAppFixtures: readonly string[];
  /** More files, relative to the repository root, that decide the manifest's content. */
  codeInputs?: string[];
};

/** The page every fixture host serves; the same shell as the root suite's `index.html` was. */
const PAGE = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Corvidae browser fixtures</title>
    <style>
      *,
      *::before,
      *::after {
        box-sizing: border-box;
      }
      html,
      body {
        margin: 0;
        min-height: 100%;
      }
      body {
        padding: clamp(var(--cinder-space-1), 2.5vw, var(--cinder-space-6));
      }
      #app {
        display: contents;
      }
    </style>
  </head>
  <body>
    <div id="app"></div>
    <script type="module" src="./main.ts"></script>
  </body>
</html>
`;

function entrySource(hostImport: string): string {
  return `// Generated by @lostgradient/testing/browser/package-suite.
import host from ${JSON.stringify(hostImport)};
import type { FixtureModuleMaps } from '@lostgradient/testing/browser/fixture-loader';
import { startFixtureHost } from '@lostgradient/testing/browser/host';

import * as modules from './fixture-modules.ts';

startFixtureHost({ ...host, modules: modules as unknown as FixtureModuleMaps });
`;
}

function posix(path: string): string {
  return path.split(sep).join('/');
}

/** The name of the file, beside the manifest, that lists the slugs a suite's sweep covers. */
export const OWNED_SLUGS_FILE = 'owned-slugs.json';

export type PackageSuite = {
  layout: ManifestLayout;
  build: FixtureBuild;
  /** Writes the manifest and the slugs this package owns. */
  prepare(): Promise<void>;
  /** Bundles the fixture page into a directory of the caller's (the chat stress capture's). */
  bundleInto(outputDirectory: string, development: boolean): Promise<void>;
  /**
   * `prepare` writes the manifest, `build` bundles the fixture page, and `serve --port <port>`
   * builds and serves it.
   */
  main(argv: string[]): Promise<void>;
};

/** Describes a package's browser suite and the command line its `harness.ts` runs. */
export function packageSuite(options: PackageSuiteOptions): PackageSuite {
  const repositoryRoot = resolve(options.root, '..', '..', '..');
  const generated = resolve(options.root, '.playwright');
  const layout: ManifestLayout = {
    repositoryRoot,
    fixtureRoots: options.fixtureRoots,
    // Module-map keys only name modules; the root suite's keys were relative to its `src`.
    sourceRoot: resolve(repositoryRoot, 'scripts', 'browser-fixtures', 'src'),
    appFixtureRoots: options.appFixtureRoots,
    appFixtureDeclarations: options.appFixtureDeclarations,
    codeInputs: [
      posix(relative(repositoryRoot, resolve(options.root, 'harness.ts'))),
      'components/*/browser/fixture-declarations.ts',
      'testing/testing/src/browser/package-suite.ts',
      'testing/testing/src/browser/prepare-manifest.ts',
      'testing/testing/src/browser/manifest.ts',
      'testing/testing/src/fixture-extraction/*.ts',
      'testing/testing/src/visual-fixtures.ts',
      'bun.lock',
      ...(options.codeInputs ?? []),
    ],
    outputDirectory: generated,
  };
  const build: FixtureBuild = {
    layout,
    indexHtml: resolve(generated, 'index.html'),
    outputDirectory: resolve(generated, 'build'),
  };

  async function prepare(): Promise<void> {
    await prepareManifest(layout);
    const owned = new Set(options.ownAppFixtures);
    const results = await Promise.all(options.ownFixtureRoots.map((root) => extractFixtures(root)));
    for (const result of results) {
      for (const entry of result.entries) owned.add(entry.componentName);
    }
    await mkdir(generated, { recursive: true });
    await Bun.write(
      resolve(generated, OWNED_SLUGS_FILE),
      `${JSON.stringify([...owned].toSorted(), null, 2)}\n`,
    );
  }

  async function writeEntry(): Promise<void> {
    await mkdir(generated, { recursive: true });
    const hostImport = posix(relative(generated, options.host));
    await Bun.write(resolve(generated, 'index.html'), PAGE);
    await Bun.write(
      resolve(generated, 'main.ts'),
      entrySource(hostImport.startsWith('.') ? hostImport : `./${hostImport}`),
    );
  }

  async function bundle(): Promise<void> {
    await writeEntry();
    await prepare();
    await buildFixtures(build, true);
  }

  async function bundleInto(outputDirectory: string, development: boolean): Promise<void> {
    await writeEntry();
    await prepare();
    await buildFixtures({ ...build, outputDirectory }, development);
  }

  async function serve(port: number): Promise<void> {
    // A Playwright run killed outright stops nothing; the host must not outlive it.
    exitWhenOrphaned();
    await bundle();
    const server = createFixtureServer({
      port,
      outputDirectory: build.outputDirectory,
      manifestPath: manifestOutputPaths(layout).manifest,
      development: true,
    });
    process.stdout.write(`fixture host listening on ${server.url}\n`);
  }

  async function main(argv: string[]): Promise<void> {
    const { positionals, values } = parseArgs({
      args: argv,
      options: { port: { type: 'string' } },
      allowPositionals: true,
      strict: true,
    });
    const [command] = positionals;
    if (command === 'prepare') {
      await prepare();
      return;
    }
    if (command === 'build') {
      await bundle();
      process.stdout.write(`built browser fixtures at ${build.outputDirectory}\n`);
      return;
    }
    if (command !== 'serve') {
      throw new Error('Usage: harness.ts prepare | build | serve --port <port>');
    }
    const port = Number(values.port);
    if (!Number.isInteger(port) || port < 0 || port > 65535) {
      throw new Error(`Invalid fixture port: ${values.port}`);
    }
    await serve(port);
  }

  return { layout, build, prepare, bundleInto, main };
}

type WorkspaceManifest = { name?: string };

/** The workspace directories under `components/`, by package name. */
function componentWorkspaces(repositoryRoot: string): Map<string, string> {
  const workspaces = new Map<string, string>();
  const components = resolve(repositoryRoot, 'components');
  for (const name of readdirSync(components)) {
    const manifestPath = resolve(components, name, 'package.json');
    if (!existsSync(manifestPath)) continue;
    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as WorkspaceManifest;
    if (typeof manifest.name === 'string') workspaces.set(manifest.name, resolve(components, name));
  }
  return workspaces;
}

/** The package whose `browser/host.ts` mounts every fixture: Cinder's core. */
export const HOST_PACKAGE = '@lostgradient/cinder';

type CoreManifest = {
  components?: { source?: { packageRoot?: unknown; directory?: unknown } }[];
};

/**
 * The directories that hold Cinder's component directories: the parent of every component
 * directory core's manifest lists, so core's own `src/components` and each family package's. Each
 * is scanned whole, as the single Cinder root was, so the fixtures beside the components and in
 * underscore directories stay in. Core keeps the fixtures that mount components of several
 * packages in its `src/component-tests` (COR-2091).
 */
export function cinderComponentRoots(coreRoot: string): string[] {
  const manifestPath = resolve(coreRoot, '.metadata', 'components.json');
  if (!existsSync(manifestPath)) {
    throw new Error(
      `${manifestPath} is missing: run \`bunx turbo run metadata --filter=${HOST_PACKAGE}\` first.`,
    );
  }
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as CoreManifest;
  const roots = new Set<string>();
  for (const component of manifest.components ?? []) {
    const { packageRoot, directory } = component.source ?? {};
    if (typeof packageRoot !== 'string' || typeof directory !== 'string') {
      throw new Error(`${manifestPath} lists a component without its source directory.`);
    }
    roots.add(dirname(resolve(coreRoot, packageRoot, directory)));
  }
  const coreTests = resolve(coreRoot, 'src', 'component-tests');
  if (existsSync(coreTests)) roots.add(coreTests);
  return [...roots].toSorted();
}

type Declarations = Record<string, readonly string[]>;

function isDeclarations(value: unknown): value is Declarations {
  return (
    value !== null &&
    typeof value === 'object' &&
    !Array.isArray(value) &&
    Object.values(value).every(
      (names) => Array.isArray(names) && names.every((name) => typeof name === 'string'),
    )
  );
}

/** Every exported declarations object of a package's `browser/fixture-declarations.ts`. */
async function readDeclarations(path: string): Promise<Declarations> {
  const module = (await import(path)) as Record<string, unknown>;
  const merged: Declarations = {};
  for (const value of Object.values(module)) {
    if (!isDeclarations(value)) continue;
    for (const [component, names] of Object.entries(value)) {
      if (Object.hasOwn(merged, component)) {
        throw new Error(`${path} declares '${component}' twice.`);
      }
      merged[component] = names;
    }
  }
  return merged;
}

/**
 * The suite of the component package whose `browser/` directory is `root`: the repository's whole
 * fixture page (every package's fixture roots, application fixtures and declarations, with core's
 * host), and the fixtures the package itself owns. Every package's `harness.ts` is this one call.
 */
export async function repositoryPackageSuite(root: string): Promise<PackageSuite> {
  const packageRoot = resolve(root, '..');
  const repositoryRoot = resolve(packageRoot, '..', '..');
  const workspaces = componentWorkspaces(repositoryRoot);
  const coreRoot = workspaces.get(HOST_PACKAGE);
  if (coreRoot === undefined) throw new Error(`No workspace under components/ is ${HOST_PACKAGE}.`);
  const directories = [...workspaces.values()].toSorted();
  const fixtureRoots = [...cinderComponentRoots(coreRoot)];
  // The chat components' own fixtures, which the root suite also served (COR-2080).
  const chatComponents = resolve(repositoryRoot, 'components', 'chat', 'src', 'lib', 'components');
  if (existsSync(chatComponents)) fixtureRoots.push(chatComponents);
  const appFixtureRoots = directories
    .map((directory) => resolve(directory, 'browser', 'fixtures'))
    .filter((directory) => existsSync(directory));
  const declarations: Declarations = {};
  let ownAppFixtures: string[] = [];
  for (const directory of directories) {
    const path = resolve(directory, 'browser', 'fixture-declarations.ts');
    if (!existsSync(path)) continue;
    const declared = await readDeclarations(path);
    for (const [component, names] of Object.entries(declared)) {
      if (Object.hasOwn(declarations, component)) {
        throw new Error(`'${component}' is declared by two packages' fixture declarations.`);
      }
      declarations[component] = names;
    }
    if (directory === packageRoot) ownAppFixtures = Object.keys(declared);
  }
  const inside = (path: string) => path === packageRoot || path.startsWith(`${packageRoot}${sep}`);
  return packageSuite({
    root,
    fixtureRoots,
    appFixtureRoots,
    appFixtureDeclarations: declarations,
    host: resolve(coreRoot, 'browser', 'host.ts'),
    ownFixtureRoots: fixtureRoots.filter(inside),
    ownAppFixtures,
    codeInputs: [
      posix(relative(repositoryRoot, resolve(coreRoot, '.metadata', 'components.json'))),
      // Modules the declarations import (the terminal's scenarios name its fixtures).
      'components/*/browser/fixtures/**/*.ts',
    ],
  });
}
