async function fixture(packScript = false, devDependencyCycle = false, binary = false) {
  const root = await mkdtemp(join(tmpdir(), 'clean-package-fixture-'));
  const target = join(root, 'target');
  const historical = join(root, 'historical');
  const surface = await Bun.file(new URL('./package-surface.json', import.meta.url)).json();
  const names = ['@lostgradient/cryptography', '@lostgradient/embeddings'];
  const entries = Object.fromEntries(
    names.map((name) => [name, structuredClone(surface.packages[name])]),
  );
  entries[names[1]!].build.packedBy = packScript ? 'pack-script' : 'files';
  await Bun.write(
    join(historical, 'scripts/mirror/package-surface.json'),
    JSON.stringify({ ...surface, packages: entries }),
  );
  await Bun.write(
    join(historical, 'scripts/mirror/verify-steps.ts'),
    `export { buildVerifySteps } from ${JSON.stringify(
      join(sourceRoot, 'scripts/mirror/verify-steps.ts'),
    )};\n`,
  );
  await Bun.write(
    join(target, 'package.json'),
    JSON.stringify({ name: 'fixture', private: true, workspaces: ['packages/*'] }),
  );
  await Bun.write(join(target, '.gitignore'), 'dist/\n*.tgz\n');
  await Bun.write(
    join(target, '.github/workflows/release.yml'),
    `steps:\n  - uses: oven-sh/setup-bun@v2\n    with:\n      bun-version: ${Bun.version}\n  - run: bun install --frozen-lockfile --linker=isolated\n`,
  );
  for (const [index, directory] of ['z-foundation', 'a-consumer'].entries()) {
    const manifest = {
      name: names[index],
      version: '1.2.3',
      files: ['dist'],
      exports: { '.': './dist/index.js' },
      ...(index === 1 && binary ? { bin: { example: './dist/index.js' } } : {}),
      scripts: { build: 'bun build.ts' },
      ...(index === 0 && devDependencyCycle
        ? { devDependencies: { [names[1]!]: 'workspace:*' } }
        : {}),
      ...(index === 1 ? { dependencies: { [names[0]!]: 'workspace:*' } } : {}),
    };
    await Bun.write(
      join(target, 'packages', directory, 'package.json'),
      JSON.stringify(manifest, null, 2) + '\n',
    );
    await Bun.write(
      join(target, 'packages', directory, 'build.ts'),
      `${index === 1 ? 'if (!(await Bun.file("../z-foundation/dist/index.js").exists())) throw new Error("Dependency was not built first");' : ''}\nawait Bun.write("dist/index.js", "export const value = 1;\\n");`,
    );
  }
  if (packScript) {
    await Bun.write(
      join(target, 'packages/a-consumer/scripts/pack-for-publish.ts'),
      `
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const status = await Bun.$\`git status --porcelain\`.quiet();
if (status.stdout.toString().trim()) throw new Error('Pack script requires a clean checkout');
const revision = (await Bun.$\`git rev-parse HEAD\`.quiet()).stdout.toString().trim();
const stage = await mkdtemp(join(tmpdir(), 'clean-package-stage-'));
try {
  const manifest = await Bun.file('package.json').json();
  manifest.gitHead = revision;
  manifest.description = 'Generated by the publication pack script';
  manifest.dependencies['@lostgradient/cryptography'] = '1.2.3';
  await Bun.write(join(stage, 'package.json'), JSON.stringify(manifest, null, 2) + '\\n');
  await Bun.write(join(stage, 'dist/index.js'), await Bun.file('dist/index.js').bytes());
  const packed = Bun.spawn(['bun', 'pm', 'pack', '--ignore-scripts', '--quiet', '--destination', process.cwd()], {cwd:stage,stdout:'pipe',stderr:'pipe'});
  await Promise.all([new Response(packed.stdout).text(), new Response(packed.stderr).text()]);
  if (await packed.exited !== 0) throw new Error('Fixture pack failed');
} finally { await rm(stage, {recursive:true,force:true}); }
`,
    );
  }
  await requireGit(target, ['init', '--quiet', '--initial-branch=main']);
  await requireGit(target, ['config', 'user.email', 'fixture@example.test']);
  await requireGit(target, ['config', 'user.name', 'Fixture']);
  await requireGit(target, ['add', '-A']);
  await requireGit(target, ['commit', '--quiet', '-m', 'Release fixture']);
  const gitHead = await requireGit(target, ['rev-parse', 'HEAD']);
  return {
    root,
    options: {
      targetRepositoryDirectory: target,
      gitHead,
      publishedSourceRoot: historical,
      workspace: names[1]!,
      publicName: names[1]!,
      targetDirectory: 'packages/a-consumer',
    },
    async [Symbol.asyncDispose]() {
      await rm(root, { recursive: true, force: true });
    },
  };
}

function recorder(failure?: 'version' | 'build') {
  const commands: {
    command: readonly string[];
    cwd: string;
    environment: Record<string, string | undefined> | undefined;
  }[] = [];
  let checkout = '';
  const runner: CommandRunner = async (command, options) => {
    commands.push({ command, cwd: options.cwd, environment: options.env });
    if (command.includes('clone')) checkout = command.at(-1)!;
    if (command[1] === 'install')
      return { command: command.join(' '), stdout: '', stderr: '', exitCode: 0 };
    if (failure === 'version' && command[1] === '--version')
      return { command: command.join(' '), stdout: '0.0.0', stderr: '', exitCode: 0 };
    if (failure === 'build' && command[2] === 'build')
      return {
        command: command.join(' '),
        stdout: '',
        stderr: 'intentional build failure',
        exitCode: 1,
      };
    return runCommand(command, options);
  };
  return { runner, commands, checkout: () => checkout };
}

type Fixture = Awaited<ReturnType<typeof fixture>>;
type Recorder = ReturnType<typeof recorder>;
type BuildOutcome = PromiseSettledResult<Awaited<ReturnType<typeof buildCleanPublishedPackage>>>;
type BuildRun = { input: Fixture; observed: Recorder; outcome: BuildOutcome };

// Every fixture and clean build runs once here, at module scope, rather than in
// a test body: each is a real git clone, build and npm pack, and under host load
// that subprocess work does not belong on bun's per-test clock (COR-1316,
// COR-1331). Test bodies assert on the captured outcomes.
const fixtures: Fixture[] = [];
afterAll(async () => {
  // Dispose every fixture even if one removal fails, then report all failures.
  const results = await Promise.allSettled(fixtures.map((input) => input[Symbol.asyncDispose]()));
  const failures = results.flatMap((result) =>
    result.status === 'rejected' ? [result.reason] : [],
  );
  if (failures.length > 0)
    throw new AggregateError(failures, 'clean-package fixture cleanup failed');
});

async function prepared(...options: Parameters<typeof fixture>): Promise<Fixture> {
  const input = await fixture(...options);
  fixtures.push(input);
  return input;
}

async function build(input: Fixture, failure?: 'version' | 'build'): Promise<BuildRun> {
  const observed = recorder(failure);
  const [outcome] = await Promise.allSettled([
    buildCleanPublishedPackage({ ...input.options, runner: observed.runner }),
  ]);
  return { input, observed, outcome };
}

/** The captured outcome as a promise again, so a test awaits or rejects it exactly as before. */
function replay<T>(outcome: PromiseSettledResult<T>): Promise<T> {
  return outcome.status === 'fulfilled'
    ? Promise.resolve(outcome.value)
    : Promise.reject(outcome.reason);
}

async function withHistoricalRecipe(recipe: string | undefined): Promise<Fixture> {
  const input = await prepared();
  const recipePath = join(input.root, 'historical/scripts/mirror/verify-steps.ts');
  if (recipe === undefined) await rm(recipePath);
  else await Bun.write(recipePath, recipe);
  return input;
}

const executableRun = await build(await prepared(false, false, true));
const dependencyOrderRun = await build(await prepared());
const devDependencyCycleRun = await build(await prepared(false, true));
const packScriptRun = await build(await prepared(true));
const historicalRecipeRun = await build(
  await (async () => {
    const input = await prepared();
    const historicalRecipeDirectory = join(input.root, 'historical/scripts/mirror');
    await mkdir(historicalRecipeDirectory, { recursive: true });
    await Bun.write(
      join(historicalRecipeDirectory, 'verify-steps.ts'),
      `import { buildVerifySteps as currentBuildVerifySteps } from ${JSON.stringify(
        join(sourceRoot, 'scripts/mirror/verify-steps.ts'),
      )};
export function buildVerifySteps(inputs, environment) {
  return currentBuildVerifySteps(inputs, environment).map((step) =>
    step.kind === 'build' ? { ...step, command: [...step.command, '--historical'] } : step,
  );
}
`,
    );
    return input;
  })(),
);
const refusedRecipeRuns = {
  missing: await build(await withHistoricalRecipe(undefined)),
  incompatible: await build(await withHistoricalRecipe('export const buildVerifySteps = 42;\n')),
};
const failedBuildInput = await prepared();
const failedBuildRuns = {
  version: await build(failedBuildInput, 'version'),
  build: await build(failedBuildInput, 'build'),
};

test('packs executable declarations with the npm publish file-mode semantics', async () => {
  const { observed, outcome } = executableRun;
  const result = await replay(outcome);
  expect(
    observed.commands.some(
      ({ command }) =>
        command[0] === 'npm' &&
        command[1] === 'pack' &&
        command.includes('--ignore-scripts') &&
        command.includes('--pack-destination'),
    ),
  ).toBe(true);
  expect(result.payload.files.find(({ path }) => path === 'package/dist/index.js')).toEqual({
    path: 'package/dist/index.js',
    executable: false,
  });
});

test('builds dependencies first, preserves release install arguments, and packs committed workspace versions', async () => {
  const { observed, outcome } = dependencyOrderRun;
  const result = await replay(outcome);
  expect(
    observed.commands
      .filter(({ command }) => command[2] === 'build')
      .map(({ cwd }) => basename(cwd)),
  ).toEqual(['z-foundation', 'a-consumer']);
  expect(
    observed.commands.find(({ command }) => command[1] === 'install')?.command.slice(1),
  ).toEqual(['install', '--frozen-lockfile', '--linker=isolated']);
  expect(result.manifest['dependencies']).toEqual({ '@lostgradient/cryptography': '1.2.3' });
  expect(result.payload.files.map(({ path }) => path)).toEqual([
    'package/dist/index.js',
    'package/package.json',
  ]);
  for (const { environment } of observed.commands) {
    expect(environment).not.toHaveProperty('GITHUB_TOKEN');
    expect(environment).not.toHaveProperty('MIRROR_APP_PRIVATE_KEY');
    expect(environment).not.toHaveProperty('NODE_AUTH_TOKEN');
    expect(environment?.['PATH']?.split(':')[0]).toBe(
      process.execPath.slice(0, process.execPath.lastIndexOf('/')),
    );
  }
  expect(await Bun.file(join(observed.checkout(), 'package.json')).exists()).toBe(false);
});

test('ignores dev-only dependency cycles while preserving runtime build order', async () => {
  const { observed, outcome } = devDependencyCycleRun;
  const result = await replay(outcome);
  expect(
    observed.commands
      .filter(({ command }) => command[2] === 'build')
      .map(({ cwd }) => basename(cwd)),
  ).toEqual(['z-foundation', 'a-consumer']);
  expect(result.payload.files.map(({ path }) => path)).toEqual([
    'package/dist/index.js',
    'package/package.json',
  ]);
});

test('uses historical pack-script policy and returns its generated manifest from a clean checkout', async () => {
  const { input, observed, outcome } = packScriptRun;
  const result = await replay(outcome);
  expect(result.manifest['gitHead']).toBe(input.options.gitHead);
  expect(result.manifest['description']).toBe('Generated by the publication pack script');
  expect(
    observed.commands.some(({ command }) => command[2] === 'scripts/pack-for-publish.ts'),
  ).toBe(true);
  expect(
    observed.commands.some(
      ({ command, cwd }) => command[0] === 'npm' && basename(cwd) === 'a-consumer',
    ),
  ).toBe(false);
  expect(await Bun.file(join(observed.checkout(), 'package.json')).exists()).toBe(false);
});

test('executes the verified historical build-step recipe', async () => {
  const { observed, outcome } = historicalRecipeRun;
  await replay(outcome);
  expect(observed.commands.filter(({ command }) => command[2] === 'build')).toHaveLength(2);
  expect(
    observed.commands
      .filter(({ command }) => command[2] === 'build')
      .every(({ command }) => command[3] === '--historical'),
  ).toBe(true);
});

test.each(['missing', 'incompatible'] as const)(
  'fails closed when the historical recipe is %s',
  async (kind) => {
    const { observed, outcome } = refusedRecipeRuns[kind];
    expect(await throwingRejectionOf(replay(outcome))).toThrow(
      kind === 'missing' ? 'recipe is missing' : 'recipe is incompatible',
    );
    expect(
      observed.commands.some(
        ({ command }) =>
          command[2] === 'build' ||
          command[1] === 'pm' ||
          command[2] === 'scripts/pack-for-publish.ts',
      ),
    ).toBe(false);
    expect(await Bun.file(join(observed.checkout(), 'package.json')).exists()).toBe(false);
  },
);

test('fails closed on a mismatched runtime or failed build and removes the scratch checkout', async () => {
  for (const failure of ['version', 'build'] as const) {
    const { observed, outcome } = failedBuildRuns[failure];
    expect(await throwingRejectionOf(replay(outcome))).toThrow(
      failure === 'version' ? 'pins Bun' : 'intentional build failure',
    );
    expect(await Bun.file(join(observed.checkout(), 'package.json')).exists()).toBe(false);
    expect(observed.commands.some(({ command }) => command[1] === 'pm')).toBe(false);
  }
});

