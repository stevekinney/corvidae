import { fixtureRoute } from '@lostgradient/testing/playwright/editor-fixture';
import { expect, test } from '@playwright/test';

test('reactive scoped reads and explicit commands use the generated client', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(fixtureRoute('backchannel-svelte'));
  await expect(page.getByTestId('read')).toHaveText('a-first');
  await expect(page.getByTestId('hydration')).toHaveText('one');
  await expect(page.getByTestId('hydration-reads')).toHaveText('0');
  await expect(page.getByTestId('writes')).toHaveText('0');
  await page.getByRole('button', { name: 'Connect events' }).click();
  await expect(page.getByTestId('events')).toHaveText('one,two');
  await page.getByRole('button', { name: 'Connect events' }).click();
  await expect(page.getByTestId('cursors')).toHaveText('start,2');
  await expect(page.getByTestId('events')).toHaveText('one,two');
  await page.evaluate(() => window.dispatchEvent(new Event('online')));
  await expect(page.getByTestId('writes')).toHaveText('0');
  await page.getByRole('button', { name: 'Initial fault' }).click();
  await expect(page.getByTestId('initial-error')).toHaveText('read failed');
  await expect(page.getByTestId('refresh-error')).toHaveText('');
  await page.getByRole('button', { name: 'Change input' }).click();
  await expect(page.getByTestId('read')).toHaveText('a-second');
  await page.getByRole('button', { name: 'Fail next refresh' }).click();
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await expect(page.getByTestId('refresh-error')).toHaveText('read failed');
  await expect(page.getByTestId('initial-error')).toHaveText('');
  await page.getByRole('button', { name: 'Start late read' }).click();
  await expect(page.getByTestId('late-started')).toHaveText('true');
  await page.getByRole('button', { name: 'Change input' }).click();
  await expect(page.getByTestId('read')).toHaveText('a-second');
  await expect(page.getByTestId('aborted')).toHaveText('1');
  await page.getByRole('button', { name: 'Resolve late read' }).click();
  await expect(page.getByTestId('read')).toHaveText('a-second');
  await page.getByRole('button', { name: 'Submit delayed' }).click();
  await page.getByRole('button', { name: 'Change scope' }).click();
  await expect(page.getByTestId('read')).toHaveText('b-second');
  await expect(page.getByTestId('observer-disconnects')).toHaveText('1');
  await expect(page.getByTestId('streams-aborted')).toHaveText('2');
  await page.getByRole('button', { name: 'Resolve delayed command' }).click();
  await expect(page.getByTestId('secret')).toHaveText('');
  await page.getByRole('button', { name: 'Submit', exact: true }).click();
  await expect(page.getByTestId('secret')).toHaveText('synthetic-once-secret');
  await expect(page.getByTestId('writes')).toHaveText('2');
  await page.getByRole('button', { name: 'Inspect state' }).click();
  await expect(page.getByTestId('inspection')).not.toContainText('synthetic-once-secret');
  await expect(page.getByTestId('inspection')).not.toContainText('stale-secret');
  await page.getByRole('button', { name: 'Submit ambiguous' }).click();
  await expect(page.getByTestId('command-fault')).toHaveText('unknown');
  await expect(page.getByTestId('writes')).toHaveText('3');
  await page.getByRole('button', { name: 'Reconcile' }).click();
  await expect(page.getByTestId('command-fault')).toHaveText('');
  await page.getByRole('button', { name: 'Submit', exact: true }).click();
  await expect(page.getByTestId('writes')).toHaveText('4');
  expect(errors).toEqual([]);
});
