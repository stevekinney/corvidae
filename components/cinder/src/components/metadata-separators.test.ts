import { describe, expect, test } from 'bun:test';
import { readdirSync, readFileSync } from 'node:fs';

/**
 * No comma between metadata pieces (COR-2445 AC12). Pieces are told apart by a space and a step in
 * weight or colour, never by a drawn "," or a middle dot. StackedListItem's own test (COR-2449)
 * holds its rule; this one holds it for ApprovalCard and ToolCallRail. StatusDot's word with a
 * qualifier is held by the branch that owns its `qualifier` prop.
 */
const components = ['approval-card', 'tool-call-rail'] as const;

function sources(component: string): { file: string; text: string }[] {
  const directory = new URL(`./${component}/`, import.meta.url);
  return readdirSync(directory)
    .filter((file) => /\.(svelte|css)$/.test(file))
    .map((file) => ({ file, text: readFileSync(new URL(file, directory), 'utf8') }));
}

describe('metadata pieces are not separated by a comma (COR-2445)', () => {
  for (const component of components) {
    test(`${component} draws no comma separator element and generates no comma`, () => {
      for (const { file, text } of sources(component)) {
        const label = `${component}/${file}`;
        // A visible "," in its own element.
        expect(text, `${label} has a comma element`).not.toMatch(/>\s*,\s*<\/span/);
        expect(text, `${label} has a separator element`).not.toMatch(
          /class="[^"]*-separator[^"]*"/,
        );
        // A comma generated by a stylesheet.
        expect(text, `${label} generates a comma`).not.toMatch(/content:\s*['"],\s?['"]/);
      }
    });
  }

  test('ApprovalCard tells its pieces apart by a gap and a step, not a comma', () => {
    const css = readFileSync(new URL('./approval-card/approval-card.css', import.meta.url), 'utf8');
    expect(css).toMatch(
      /\.cinder-approval-card__line-tool:has\(\*\) \+ \.cinder-approval-card__line-source[^{]*\{\s*margin-inline-start: var\(--cinder-space-1-5\);/,
    );
    expect(css).toMatch(
      /\.cinder-approval-card__tool-label \{[^}]*font-weight: var\(--cinder-font-medium\)/,
    );
    expect(css).toMatch(
      /\.cinder-approval-card__risk-word \{[^}]*color: var\(--cinder-text-subtle\)/,
    );
    expect(css).toMatch(/time,[^{]*\{\s*font-variant-numeric: tabular-nums/s);
  });

  test('ToolCallRail tells its counts and duration apart by the summary gap and a colour step', () => {
    const css = readFileSync(
      new URL('./tool-call-rail/tool-call-rail.css', import.meta.url),
      'utf8',
    );
    expect(css).toMatch(/\.cinder-tool-call-rail__summary \{[^}]*gap: var\(--cinder-space-1-5\)/);
    expect(css).toMatch(
      /\.cinder-tool-call-rail__summary-duration \{[^}]*color: var\(--cinder-text-subtle\)/,
    );
  });
});
