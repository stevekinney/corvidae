/**
 * COR-713 — generated media through Bureau: an image a model returns is admitted as a managed asset
 * as the run's owner before any hook, event, row or persisted result sees it; a refused or cancelled
 * admission ends the run typed; and `closed()` waits for every admission the run started.
 */
import {
  createAgent,
  createModelCatalog,
  GeneratedMediaNotAdmittedError,
  type GenerateContext,
  type GenerateResponse,
  withBackendDescriptors,
  withEnhancedStreaming,
  withStreaming,
} from '@lostgradient/operative';
import { yieldToPortableEventLoop } from '@lostgradient/weft';
import { afterEach, describe, expect, it } from 'bun:test';

import { closedTask, runTask } from './test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { createAssetGeneratedMediaAdmitter } from './assets/generated-media-admitter';
import { createBureau } from './create-bureau';
import { createMemoryAssetStorageFixture } from './test/asset-storage-fixtures';
import { alice, base64Of, bob, pngBytes } from './testing/asset-fixtures.test-support';

const cleanups: Array<() => Promise<void>> = [];
afterEach(async () => {
  while (cleanups.length > 0) await cleanups.pop()!();
  // load-proof: the work this lets finish runs on in-memory storage and doubles and settles through promise continuations only, so a microtask drain completes it (checked by replacing the turn with one); no timer or I/O is pending
  await yieldToPortableEventLoop();
});

/** A backend whose descriptor advertises image output, which no catalog row does. */
const imageOutputDescriptors = createModelCatalog()
  .descriptors.filter((descriptor) => descriptor.provider === 'anthropic')
  .slice(0, 1)
  .map((descriptor) => ({
    ...descriptor,
    modalities: {
      ...descriptor.modalities,
      image: { ...descriptor.modalities.image, output: true },
    },
  }));

const generatedPng = pngBytes(4, 3);
const inlineImage = {
  type: 'image' as const,
  mimeType: 'image/png',
  source: { kind: 'inline' as const, data: base64Of(generatedPng), encoding: 'base64' as const },
};
const imageResponse: GenerateResponse = {
  content: 'Here it is.',
  parts: [{ type: 'text', text: 'Here it is.' }, inlineImage],
  toolCalls: [],
};

function paintingAgent(seen: GenerateContext[] = []) {
  return createAgent({
    generate: withBackendDescriptors(async (context: GenerateContext) => {
      seen.push(context);
      return imageResponse;
    }, imageOutputDescriptors),
  });
}

async function openBureau(
  options: {
    durable?: boolean;
    policy?: import('./assets/types').AssetPolicyInput;
    ports?: NonNullable<Parameters<typeof createBureau>[0]['assets']>['ports'];
  } = {},
  agent = paintingAgent(),
) {
  const fixture = createMemoryAssetStorageFixture({});
  cleanups.push(() => fixture.dispose());
  const bureau = await createBureau({
    agents: { painter: agent },
    assets: {
      storage: fixture.storage,
      ...(options.policy === undefined ? {} : { policy: options.policy }),
      ...(options.ports === undefined ? {} : { ports: options.ports }),
    },
    ...(options.durable ? { storage: { type: 'memory' as const }, durable: true } : {}),
  });
  cleanups.push(async () => {
    await bureau.dispose();
  });
  return bureau;
}

describe.each([false, true])('a generated image through Bureau (durable: %p)', (durable) => {
  it('is admitted as a managed asset the run owner may read, and no result shape holds the bytes', async () => {
    const bureau = await openBureau({ durable });
    const run = await bureau.tasks.start('painter', 'Draw', { principal: alice.id });

    const result = await run.result();

    expect(result.finishReason).not.toBe('error');
    const image = result.parts.find((part) => part.type === 'image');
    expect(image).toMatchObject({
      type: 'image',
      mimeType: 'image/png',
      source: { kind: 'managed-asset' },
    });
    const source = (image as { source: { assetId: string; revision?: number } }).source;
    expect(result.steps[0]?.parts).toEqual(result.parts);

    const row = result.conversation.getMessages().find((message) => message.role === 'assistant');
    expect(row?.content).toEqual(result.parts);
    expect(row?.id).toBe(result.steps[0]?.messageId);

    // The asset is available to its owner and to nobody else.
    const descriptor = await bureau.assets!.inspect(source.assetId, alice);
    expect(descriptor.state).toBe('available');
    expect(descriptor.owner).toBe(alice.id);
    expect(descriptor.mediaType).toBe('image/png');
    const resolved = await bureau.assets!.resolve(source, alice);
    expect(resolved.content).toEqual({ kind: 'bytes', bytes: generatedPng });
    let denied: unknown;
    try {
      await bureau.assets!.resolve(source, bob);
    } catch (error) {
      denied = error;
    }
    expect(denied).toBeDefined();

    // No serialized form of the result carries the generated bytes.
    expect(JSON.stringify(result.parts)).not.toContain(base64Of(generatedPng));
    expect(JSON.stringify(result.conversation.current)).not.toContain(base64Of(generatedPng));

    // closed() waits for the admission and acknowledges it.
    expect(await closedTask(bureau, run)).toEqual({ status: 'completed' });
    expect(bureau.assets!.activeWork()).toEqual([]);
  });

  it('ends the run with finishReason error, naming the part, when the policy refuses the admission, and closed() is completed', async () => {
    const bureau = await openBureau({ durable, policy: { maxAssetBytes: 8 } });
    const run = await bureau.tasks.start('painter', 'Draw', { principal: alice.id });

    const result = await run.result();

    expect(result.finishReason).toBe('error');
    expect(result.error).toBeInstanceOf(GeneratedMediaNotAdmittedError);
    const error = result.error as GeneratedMediaNotAdmittedError;
    expect(error.reason).toBe('admission-failed');
    expect(error.partIndex).toBe(1);
    expect(error.rejectionCode).toBe('per-part-limit-exceeded');
    expect(error.message).toContain('part 1');
    expect(await closedTask(bureau, run)).toEqual({ status: 'completed' });
    expect(bureau.assets!.activeWork()).toEqual([]);
  });
});

describe('cancelling a run while its generated image is being admitted', () => {
  it('aborts the admission, so no descriptor stays pending once closed() resolves', async () => {
    let reachedExtraction!: () => void;
    const extracting = new Promise<void>((resolve) => {
      reachedExtraction = resolve;
    });
    const bureau = await openBureau({
      ports: {
        // Parks the admission until the run's cancellation reaches it.
        extractMetadata: async ({ signal }) => {
          reachedExtraction();
          await new Promise<void>((resolve) => {
            if (signal.aborted) resolve();
            else signal.addEventListener('abort', () => resolve(), { once: true });
          });
          signal.throwIfAborted();
          return {};
        },
      },
    });
    const run = await bureau.tasks.start('painter', 'Draw', { principal: alice.id });

    await extracting;
    const [pending] = bureau.assets!.activeWork();
    expect(pending?.workKind).toBe('admission');
    run.abort('stop');
    const result = await run.result();
    const acknowledgement = await closedTask(bureau, run, { signal: new AbortController().signal });

    expect(result.finishReason).toBe('aborted');
    expect(['completed', 'unresolved']).toContain(acknowledgement.status);
    if (acknowledgement.status === 'unresolved') {
      expect(acknowledgement.reason).toBe('unknown-effect');
    }
    expect(bureau.assets!.activeWork()).toEqual([]);
    const descriptor = await bureau.assets!.inspect(pending!.assetId!, alice);
    expect(descriptor.state).toBe('rejected');
    expect(descriptor.rejection?.code).toBe('aborted');
  });
});

describe('a durable run restarted over SQLite (COR-713)', () => {
  it('keeps the run-wide parts, the committed row id and the asset after a new Bureau opens the same store', async () => {
    const directory = await mkdtemp(join(tmpdir(), 'bureau-generated-media-'));
    const storagePath = join(directory, 'bureau');
    cleanups.push(async () => {
      await rm(directory, { recursive: true, force: true });
    });
    const open = async () => {
      const bureau = await createBureau({
        agents: { painter: paintingAgent() },
        assets: { storage: createMemoryAssetStorageFixture({}).storage },
        storage: { type: 'sqlite', path: storagePath },
        durable: true,
      });
      cleanups.push(async () => {
        await bureau.dispose();
      });
      return bureau;
    };

    const first = await open();
    const run = await first.tasks.start('painter', 'Draw', { principal: alice.id });
    const result = await run.result();
    expect(result.finishReason).not.toBe('error');
    await closedTask(first, run);
    const image = result.parts.find((part) => part.type === 'image');
    expect(image).toMatchObject({ source: { kind: 'managed-asset' } });
    const runId = run.id;
    await first.dispose();

    const second = await open();
    const durable = await second.tasks.workflow(runId);
    expect(durable?.status).toBe('completed');
    const summary = durable?.result as { schemaVersion: number; parts: typeof result.parts };
    expect(summary.schemaVersion).toBe(3);
    expect(summary.parts).toEqual(result.parts);
    expect(JSON.stringify(summary)).not.toContain(base64Of(generatedPng));
  });
});

describe('a Bureau without an asset service', () => {
  it('fails a generated media part typed at its admission point', async () => {
    const bureau = await createBureau({ agents: { painter: paintingAgent() } });
    cleanups.push(async () => {
      await bureau.dispose();
    });

    const result = await runTask(bureau, 'painter', 'Draw');

    expect(result.finishReason).toBe('error');
    expect(result.error).toBeInstanceOf(GeneratedMediaNotAdmittedError);
    expect((result.error as GeneratedMediaNotAdmittedError).reason).toBe('no-admitter');
  });
});

describe('aggregate limits across the generated parts of one response (correction)', () => {
  it('refuses parts that are each within the limit but exceed it together', async () => {
    const size = generatedPng.byteLength;
    const twoImages = createAgent({
      generate: withBackendDescriptors(
        async () => ({
          content: '',
          parts: [inlineImage, { ...inlineImage }],
          toolCalls: [],
        }),
        imageOutputDescriptors,
      ),
    });
    const bureau = await openBureau(
      {
        policy: {
          limits: [
            { scope: 'aggregate', modality: 'image', maxBytes: size + Math.floor(size / 2) },
          ],
        },
      },
      twoImages,
    );

    const run = await bureau.tasks.start('painter', 'Draw', { principal: alice.id });
    const result = await run.result();

    expect(result.finishReason).toBe('error');
    expect(result.error).toBeInstanceOf(GeneratedMediaNotAdmittedError);
    expect((result.error as GeneratedMediaNotAdmittedError).rejectionCode).toBe(
      'aggregate-limit-exceeded',
    );
    expect(await closedTask(bureau, run)).toEqual({ status: 'completed' });
    expect(bureau.assets!.activeWork()).toEqual([]);
  });
});

describe('the admission abort listener (correction)', () => {
  it('is removed from the step signal once the admission settles', async () => {
    const bureau = await openBureau();
    let added = 0;
    let removed = 0;
    const listeners = new Set<unknown>();
    const signal = {
      aborted: false,
      addEventListener: (_type: string, listener: unknown) => {
        added += 1;
        listeners.add(listener);
      },
      removeEventListener: (_type: string, listener: unknown) => {
        removed += 1;
        listeners.delete(listener);
      },
    } as unknown as AbortSignal;

    const admission = await createAssetGeneratedMediaAdmitter(bureau.assets!, alice.id).admit({
      part: inlineImage,
      runId: 'run-1',
      step: 0,
      partIndex: 0,
      messageId: undefined,
      signal,
    });
    const settlement = await admission.settled();
    expect(settlement.outcome).toBe('available');
    await admission.closed();

    expect(added).toBe(1);
    expect(removed).toBe(1);
    expect(listeners.size).toBe(0);
  });
});

describe('streamed generated media under an aggregate limit (correction 2)', () => {
  /** A streamed backend that reports two completed images and returns them. */
  function streamedPainter(wrapper: typeof withStreaming | typeof withEnhancedStreaming) {
    const images = [inlineImage, { ...inlineImage }];
    return createAgent({
      generate: withBackendDescriptors(
        wrapper(async ({ streaming }) => {
          for (const [partIndex, part] of images.entries()) {
            streaming.reportPart?.({ type: 'start', partIndex, kind: 'image' });
            streaming.reportPart?.({ type: 'complete', partIndex, part });
          }
          return { content: '', parts: images, toolCalls: [] };
        }),
        imageOutputDescriptors,
      ),
    });
  }

  const wrappers = [
    ['withStreaming', withStreaming],
    ['withEnhancedStreaming', withEnhancedStreaming],
  ] as const;

  it.each(wrappers)(
    'refuses a streamed image when its type has an aggregate limit (%s)',
    async (_name, wrapper) => {
      // Two images of 0.6 of the limit each: valid alone, over the limit together.
      const limit = Math.floor(generatedPng.byteLength / 0.6);
      const bureau = await openBureau(
        { policy: { limits: [{ scope: 'aggregate', modality: 'image', maxBytes: limit }] } },
        streamedPainter(wrapper),
      );

      const run = await bureau.tasks.start('painter', 'Draw', { principal: alice.id });
      const result = await run.result();

      expect(result.finishReason).toBe('error');
      expect(result.error).toBeInstanceOf(GeneratedMediaNotAdmittedError);
      const error = result.error as GeneratedMediaNotAdmittedError;
      expect(error.reason).toBe('admission-failed');
      expect(error.message).toContain('aggregate image limit');
      // The part was refused before any asset record was written, so nothing was left to wait for.
      expect(await closedTask(bureau, run)).toEqual({ status: 'not-required' });
      expect(bureau.assets!.activeWork()).toEqual([]);
    },
  );

  it.each(wrappers)(
    'admits a streamed image when no aggregate limit is set (%s)',
    async (_name, wrapper) => {
      const bureau = await openBureau({}, streamedPainter(wrapper));

      const run = await bureau.tasks.start('painter', 'Draw', { principal: alice.id });
      const result = await run.result();

      expect(result.finishReason).not.toBe('error');
      expect(result.parts.filter((part) => part.type === 'image')).toHaveLength(2);
      expect(await closedTask(bureau, run)).toEqual({ status: 'completed' });
    },
  );

  it('a per-part limit alone does not stop a streamed image', async () => {
    const bureau = await openBureau(
      {
        policy: {
          limits: [{ scope: 'per-part', modality: 'image', maxBytes: generatedPng.byteLength * 2 }],
        },
      },
      streamedPainter(withStreaming),
    );

    const result = await runTask(bureau, 'painter', 'Draw', { principal: alice.id });

    expect(result.finishReason).not.toBe('error');
  });
});

describe('a streamed part whose bytes are a type with an aggregate limit (correction 3)', () => {
  // The service counts a part against the aggregate budget of the media type it detects from the
  // bytes, so the refusal must too: a declared `type` or a missing `mimeType` cannot route around it.
  const untypedPng = {
    type: 'file' as const,
    source: { kind: 'inline' as const, data: base64Of(generatedPng), encoding: 'base64' as const },
  };
  const neverAborted = new AbortController().signal;

  it('refuses a PNG declared as an untyped file part under an aggregate image limit', async () => {
    const bureau = await openBureau({
      policy: {
        limits: [{ scope: 'aggregate', modality: 'image', maxBytes: generatedPng.byteLength * 10 }],
      },
    });
    const admitter = createAssetGeneratedMediaAdmitter(bureau.assets!, alice.id);

    let refusal: unknown;
    try {
      await admitter.admit({
        part: untypedPng,
        runId: 'run-1',
        step: 0,
        partIndex: 0,
        messageId: undefined,
        signal: neverAborted,
      });
    } catch (error) {
      refusal = error;
    }

    expect((refusal as { code?: string } | undefined)?.code).toBe('aggregate-limit-exceeded');
    expect(bureau.assets!.activeWork()).toEqual([]);
  });

  // The refusal counts the type the service counts, which reconciles the declaration with the
  // bytes, so a part the service would count as another type is not refused under this one's limit.
  const zipBytes = new Uint8Array([
    0x50,
    0x4b,
    0x03,
    0x04,
    ...Array.from({ length: 60 }, () => 0x20),
  ]);
  const docxPart = {
    type: 'document' as const,
    mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    source: { kind: 'inline' as const, data: base64Of(zipBytes), encoding: 'base64' as const },
  };
  const svgPart = {
    type: 'image' as const,
    mimeType: 'image/svg+xml',
    source: {
      kind: 'inline' as const,
      data: base64Of(
        new TextEncoder().encode(
          '<svg xmlns="http://www.w3.org/2000/svg" width="4" height="3"><rect width="4" height="3"/></svg>',
        ),
      ),
      encoding: 'base64' as const,
    },
  };

  it.each([
    ['an OOXML document over ZIP bytes under a file-only aggregate limit', docxPart, 'file'],
    ['an SVG image over UTF-8 bytes under a text-only aggregate limit', svgPart, 'text'],
  ] as const)('admits %s', async (_name, part, modality) => {
    const bureau = await openBureau({
      policy: { limits: [{ scope: 'aggregate', modality, maxBytes: 1 }] },
    });
    const admitter = createAssetGeneratedMediaAdmitter(bureau.assets!, alice.id);

    const admission = await admitter.admit({
      part,
      runId: 'run-1',
      step: 0,
      partIndex: 0,
      messageId: undefined,
      signal: neverAborted,
    });
    const settlement = await admission.settled();

    expect(settlement.outcome).toBe('available');
    await admission.closed();
  });

  it('admits the same untyped part when only a different type has an aggregate limit', async () => {
    const bureau = await openBureau({
      policy: { limits: [{ scope: 'aggregate', modality: 'audio', maxBytes: 1 }] },
    });
    const admitter = createAssetGeneratedMediaAdmitter(bureau.assets!, alice.id);

    const admission = await admitter.admit({
      part: untypedPng,
      runId: 'run-1',
      step: 0,
      partIndex: 0,
      messageId: undefined,
      signal: neverAborted,
    });

    const settlement = await admission.settled();
    expect(settlement.outcome).toBe('available');
    await admission.closed();
  });
});
