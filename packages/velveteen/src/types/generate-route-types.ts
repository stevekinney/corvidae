import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, relative, resolve, sep } from "node:path";
import type {
  RouteManifest,
  RouteNode,
  RouteParam,
} from "../routing/manifest-types.ts";

export type GenerateRouteTypesOptions = { outputDirectory: string };
export type GenerateRouteTypesResult = {
  files: string[];
  removed: string[];
  configuration: string;
};
const marker = "// Generated by velveteen. Do not edit.";

function contained(root: string, path: string) {
  const value = relative(root, path);
  return !isAbsolute(value) && value !== ".." && !value.startsWith(`..${sep}`);
}

function importPath(from: string, source: string) {
  const path = relative(dirname(from), source).split(sep).join("/");
  return path.startsWith(".") ? path : `./${path}`;
}

function parameters(
  params: RouteParam[],
  file: string,
  matcherModule?: string,
) {
  const fields = new Map<string, RouteParam[]>();
  for (const parameter of params) {
    const variants = fields.get(parameter.name);
    if (variants) variants.push(parameter);
    else fields.set(parameter.name, [parameter]);
  }
  if (!fields.size) return "{}";
  const valueType = ({ matcher }: RouteParam) => {
    if (!matcher) return "string";
    if (!matcherModule)
      throw new Error(`Missing module for matcher ${matcher}`);
    const source = JSON.stringify(importPath(file, matcherModule));
    return `Exclude<ReturnType<typeof import(${source}).params[${JSON.stringify(matcher)}]>, undefined>`;
  };
  const properties = [...fields].map(([name, variants]) => {
    const optional = variants.every((parameter) => parameter.optional);
    return `${JSON.stringify(name)}${optional ? "?" : ""}: ${[...new Set(variants.map(valueType))].join(" | ")}`;
  });
  return `{ ${properties.join("; ")} }`;
}

function layoutAncestors(
  node: RouteNode,
  byId: Map<string, RouteNode>,
): RouteNode[] {
  const result: RouteNode[] = [];
  let parentId = node.layoutParentId;
  const visited = new Set([node.id]);
  while (parentId !== null) {
    if (visited.has(parentId))
      throw new Error(`Cyclic route ancestry at ${node.id}`);
    visited.add(parentId);
    const parent = byId.get(parentId);
    if (!parent) throw new Error(`Missing parent ${parentId} for ${node.id}`);
    result.unshift(parent);
    parentId = parent.layoutParentId;
  }
  return result;
}

function declarations(
  manifest: RouteManifest,
  node: RouteNode,
  file: string,
  layoutParents: RouteNode[],
  pageLayouts: RouteNode[],
  layoutParameters: RouteParam[],
) {
  const module = (path: string) =>
    `typeof import(${JSON.stringify(importPath(file, resolve(manifest.routesDirectory, path)))})`;
  const load = (path: string | undefined, fallback = "{}") =>
    path ? `LoadData<${module(path)}, ${fallback}>` : fallback;
  const merge = (parent: string, child: string) => `Merge<${parent}, ${child}>`;
  const serverData = (layouts: RouteNode[]) =>
    layouts.reduce(
      (data, ancestor) => merge(data, load(ancestor.layout?.server)),
      "{}",
    );
  const universalData = (layouts: RouteNode[]) =>
    layouts.reduce(
      (data, ancestor) =>
        merge(
          data,
          load(ancestor.layout?.universal, load(ancestor.layout?.server)),
        ),
      "{}",
    );
  const ownServerLayout = load(node.layout?.server);
  const layoutData = universalData([...layoutParents, node]);
  const pageLayoutData = universalData(pageLayouts);
  const ownServerPage = load(node.page?.server);
  const actionModule = node.page?.server ? module(node.page.server) : "{}";
  const ownUniversalPage = load(node.page?.universal, ownServerPage);
  return `${marker}
import type { RequestEvent as RuntimeRequestEvent, ServerLoadEvent as RuntimeServerLoadEvent } from ${JSON.stringify(importPath(file, resolve(import.meta.dir, "../server/types.ts")))};
import type { UniversalLoadEvent } from ${JSON.stringify(importPath(file, resolve(import.meta.dir, "../data/contract.ts")))};
import type { ActionFailure } from ${JSON.stringify(importPath(file, resolve(import.meta.dir, "../actions/server.ts")))};
type LoadData<Module, Fallback = {}> = Module extends { load: (...arguments_: never[]) => infer Result } ? Awaited<Result> extends Record<string, unknown> ? Awaited<Result> : {} : Fallback;
type Merge<Parent, Child> = Omit<Parent, keyof Child> & Child;
type LoadOutput = Record<string, unknown> | void;
type ActionOutput<Module> = Module extends { actions: infer Actions } ? Actions extends Record<string, (...arguments_: never[]) => infer Result> ? UnwrapAction<Awaited<Result>> : never : never;
type UnwrapAction<Result> = Result extends ActionFailure<infer Failure> ? Failure : Result extends void ? never : Result;
export type RouteId = ${JSON.stringify(node.id)};
export type RouteParams = ${parameters(node.params, file, manifest.matcherModule)};
export type LayoutParams = ${parameters(layoutParameters, file, manifest.matcherModule)};
export type LayoutParentData = ${universalData(layoutParents)};
export type LayoutServerParentData = ${serverData(layoutParents)};
export type LayoutServerData = ${ownServerLayout};
export type LayoutData = ${layoutData};
export type PageServerData = ${ownServerPage};
export type PageData = ${merge(pageLayoutData, ownUniversalPage)};
export type RequestEvent = Omit<RuntimeRequestEvent, "params" | "route"> & { params: RouteParams; route: { id: RouteId } };
export type RequestHandler = (event: RequestEvent) => Response | Promise<Response>;
export type PageLoadEvent = Omit<UniversalLoadEvent, "params" | "route" | "data" | "parent"> & { params: RouteParams; data: PageServerData; route: { id: RouteId }; parent: () => Promise<${pageLayoutData}> };
export type PageServerLoadEvent = RequestEvent & Pick<RuntimeServerLoadEvent, "depends" | "untrack"> & { parent: () => Promise<${serverData(pageLayouts)}> };
export type LayoutLoadEvent = Omit<PageLoadEvent, "params" | "data" | "parent"> & { params: LayoutParams; data: LayoutServerData; parent: () => Promise<LayoutParentData> };
export type LayoutServerLoadEvent = Omit<PageServerLoadEvent, "params" | "parent"> & { params: LayoutParams; parent: () => Promise<LayoutServerParentData> };
export type PageLoad<Output extends LoadOutput = LoadOutput> = (event: PageLoadEvent) => Output | Promise<Output>;
export type PageServerLoad<Output extends LoadOutput = LoadOutput> = (event: PageServerLoadEvent) => Output | Promise<Output>;
export type LayoutLoad<Output extends LoadOutput = LoadOutput> = (event: LayoutLoadEvent) => Output | Promise<Output>;
export type LayoutServerLoad<Output extends LoadOutput = LoadOutput> = (event: LayoutServerLoadEvent) => Output | Promise<Output>;
type ActionResult = Record<string, unknown> | ActionFailure<Record<string, unknown>> | void;
export type Action = (event: RequestEvent) => ActionResult | Promise<ActionResult>;
export type Actions = Record<string, Action>;
export type ActionData = ActionOutput<${actionModule}>;
export type PageProps = { params: RouteParams; data: PageData; form: ActionData | null };
export type LayoutProps = { params: LayoutParams; data: LayoutData; children: import("svelte").Snippet };
`;
}

function rootDeclarations(manifest: RouteManifest, file: string) {
  const routes = [...manifest.routes].toSorted((a, b) =>
    a.id.localeCompare(b.id),
  );
  return `${marker}
export type RouteId = ${routes.map((route) => JSON.stringify(route.id)).join(" | ") || "never"};
export type RouteParameterMap = {
${routes.map((route) => `  ${JSON.stringify(route.id)}: ${parameters(route.params, file, manifest.matcherModule)};`).join("\n")}
};
export type RouteParams<Id extends RouteId = RouteId> = RouteParameterMap[Id];
`;
}

async function ownedDeclarations(directory: string): Promise<string[]> {
  const entries = await readdir(directory, { withFileTypes: true });
  const files: string[] = [];
  for (const entry of entries) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await ownedDeclarations(path)));
    } else if (entry.isFile() && entry.name.endsWith(".d.ts")) {
      const declaration = await readFile(path, "utf8");
      if (declaration.startsWith(marker)) files.push(path);
    }
  }
  return files;
}

/** Generate sibling $types imports through rootDirs; use `satisfies` to retain load return inference. */
export async function generateRouteTypes(
  manifest: RouteManifest,
  options: GenerateRouteTypesOptions,
): Promise<GenerateRouteTypesResult> {
  const outputDirectory = resolve(options.outputDirectory);
  if (
    contained(manifest.routesDirectory, outputDirectory) ||
    contained(outputDirectory, manifest.routesDirectory)
  ) {
    throw new Error(
      "Routes and generated types directories must not contain one another",
    );
  }
  const byId = new Map(manifest.nodes.map((node) => [node.id, node]));
  if (byId.size !== manifest.nodes.length)
    throw new Error("Duplicate manifest node IDs");
  const rootFile = resolve(outputDirectory, "index.d.ts");
  const writes = new Map([[rootFile, rootDeclarations(manifest, rootFile)]]);
  const pageLayouts = new Map<number, RouteNode[]>();
  const layoutParameters = manifest.nodes.map((node) => [...node.params]);
  for (const route of manifest.routes) {
    if (route.leaf === undefined) continue;
    const inherited = route.layouts.filter((index) => index !== null);
    pageLayouts.set(
      route.leaf,
      inherited.map((index) => manifest.nodes[index]),
    );
    for (const index of inherited) {
      const params = layoutParameters[index];
      for (const parameter of route.params)
        if (
          !params.some(
            (existing) =>
              existing.name === parameter.name &&
              existing.matcher === parameter.matcher,
          )
        )
          params.push({ ...parameter, optional: true });
    }
  }
  for (const [index, node] of manifest.nodes.entries()) {
    const directory = resolve(outputDirectory, node.directory);
    if (!contained(outputDirectory, directory) || isAbsolute(node.directory))
      throw new Error(`Invalid route directory ${node.directory}`);
    const file = resolve(directory, "$types.d.ts");
    const layoutParents = layoutAncestors(node, byId);
    writes.set(
      file,
      declarations(
        manifest,
        node,
        file,
        layoutParents,
        pageLayouts.get(index) ?? [...layoutParents, node],
        layoutParameters[index],
      ),
    );
  }
  const configuration = resolve(outputDirectory, "tsconfig.json");
  writes.set(
    configuration,
    marker +
      "\n" +
      JSON.stringify(
        {
          compilerOptions: {
            target: "ESNext",
            module: "Preserve",
            moduleResolution: "Bundler",
            lib: ["ESNext", "DOM", "DOM.Iterable"],
            types: ["bun"],
            strict: true,
            noEmit: true,
            skipLibCheck: false,
            isolatedModules: true,
            verbatimModuleSyntax: true,
            allowImportingTsExtensions: true,
            rootDirs: [manifest.routesDirectory, outputDirectory],
          },
          include: [
            resolve(manifest.routesDirectory, "**/*.ts"),
            resolve(manifest.routesDirectory, "**/*.svelte"),
            resolve(outputDirectory, "**/*.d.ts"),
          ],
        },
        null,
        2,
      ) +
      "\n",
  );
  await mkdir(outputDirectory, { recursive: true });
  const previous = await ownedDeclarations(outputDirectory);
  // Detect collisions before replacing any file. Generated paths never take ownership of application files.
  for (const file of writes.keys()) {
    if (!(await Bun.file(file).exists())) continue;
    const content = await readFile(file, "utf8");
    if (!content.startsWith(marker))
      throw new Error(`Refusing to replace application-owned file ${file}`);
  }
  for (const [file, content] of writes) {
    await mkdir(dirname(file), { recursive: true });
    if (
      !(await Bun.file(file).exists()) ||
      (await readFile(file, "utf8")) !== content
    )
      await writeFile(file, content);
  }
  const removed = previous.filter((file) => !writes.has(file));
  await Promise.all(removed.map((file) => rm(file)));
  return {
    files: [...writes.keys()].toSorted(),
    removed: removed.toSorted(),
    configuration,
  };
}
