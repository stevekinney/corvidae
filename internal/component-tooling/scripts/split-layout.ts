/**
 * The layout of the Cinder package split (P-COR-101), shared by `extract-families.ts`, which moves
 * core's files into packages, and `derive-families.ts`, which reads the split tree back.
 *
 * Every package keeps core's layout: a file at `<core>/src/<path>` moves to
 * `components/<package>/src/<path>`, so a relative import between two files of one package never
 * changes, and the union of every package's `src` is the tree the family map was derived from.
 * That `src/<path>` is a file's _virtual path_. An import that crosses packages names the other
 * package by specifier, and {@link specifierFor} and {@link virtualPathFor} convert between the two:
 *
 * - a family: `@lostgradient/<family>` (its barrel), `/styles` (its stylesheet), `/<component>.css`,
 *   `/components/<path>` for anything under `src/components`, and `/<path>` for a module elsewhere,
 *   which its manifest exports by name;
 * - tokens and foundation: `/<name>.css` for `src/styles/<name>.css`, and `/<path>` for the rest;
 * - the component tooling: the subpaths its own manifest exports.
 *
 * A package's barrel and stylesheet are generated: they start with {@link GENERATED_MARKER}, are
 * not part of the original tree, and stand for the files they re-export or import.
 */

import { posix } from 'node:path';

export type SplitKind = 'family' | 'foundation' | 'tokens';

export const PACKAGE_SCOPE = '@lostgradient/';
export const TOOLING_PACKAGE = '@lostgradient/component-tooling';

/** The first line of a file the extraction generates. */
export const GENERATED_MARKER =
  '@generated by internal/component-tooling/scripts/extract-families.ts';

/** The component tooling's modules that core's tree still holds, by the subpath that exports them. */
export const TOOLING_SUBPATHS: Readonly<Record<string, string>> = {
  'src/schema-types.ts': 'schema-types',
  'src/manifest.meta.ts': 'manifest.meta',
};

export function kindOf(name: string): SplitKind {
  return name === 'tokens' || name === 'foundation' ? name : 'family';
}

export function isGenerated(content: string): boolean {
  return content.slice(0, 200).includes(GENERATED_MARKER);
}

/** What names a file of another package: the specifier, and the export key it needs, if any. */
export type PackageSpecifier = { specifier: string; exportKey?: string };

/**
 * The specifier that names `path` (a virtual path) in `name`. `components` are the family's
 * component directories; a family's own component stylesheet is named `<component>.css`.
 */
export function specifierFor(
  name: string,
  path: string,
  components: readonly string[] = [],
): PackageSpecifier {
  if (name === 'tooling') {
    const subpath = TOOLING_SUBPATHS[path];
    if (subpath === undefined) throw new Error(`No tooling subpath exports ${path}.`);
    return { specifier: `${TOOLING_PACKAGE}/${subpath}` };
  }
  if (!path.startsWith('src/'))
    throw new Error(`${path} is outside src, so no package exports it.`);
  const rest = path.slice('src/'.length);
  const base = `${PACKAGE_SCOPE}${name}`;
  if (kindOf(name) !== 'family') {
    const stylesheet = /^styles\/(.+\.css)$/.exec(rest);
    if (stylesheet !== null) return { specifier: `${base}/${stylesheet[1]}` };
    return { specifier: `${base}/${rest}` };
  }
  const component = /^components\/([^/]+)\/([^/]+)\.css$/.exec(rest);
  if (
    component !== null &&
    component[1] === component[2] &&
    components.includes(component[1] ?? '')
  ) {
    return { specifier: `${base}/${component[1]}.css` };
  }
  if (rest.startsWith('components/')) return { specifier: `${base}/${rest}` };
  return { specifier: `${base}/${rest}`, exportKey: `./${rest}` };
}

/** The virtual path a package specifier names, the inverse of {@link specifierFor}. */
export function virtualPathFor(specifier: string): { name: string; path: string } | undefined {
  if (specifier.startsWith(`${TOOLING_PACKAGE}/`)) {
    const subpath = specifier.slice(TOOLING_PACKAGE.length + 1);
    const path = Object.keys(TOOLING_SUBPATHS).find((key) => TOOLING_SUBPATHS[key] === subpath);
    return path === undefined ? undefined : { name: 'tooling', path };
  }
  if (!specifier.startsWith(PACKAGE_SCOPE)) return undefined;
  const [name = '', ...parts] =
    specifier.slice(PACKAGE_SCOPE.length).split('?')[0]?.split('/') ?? [];
  const subpath = parts.join('/');
  if (subpath === '') return { name, path: 'src/index.ts' };
  if (kindOf(name) !== 'family') {
    return { name, path: subpath.endsWith('.css') ? `src/styles/${subpath}` : `src/${subpath}` };
  }
  if (subpath === 'styles') return { name, path: 'src/styles/index.css' };
  const component = /^([^/]+)\.css$/.exec(subpath);
  if (component !== null) return { name, path: `src/components/${component[1]}/${subpath}` };
  return { name, path: `src/${subpath}` };
}

/** A relative specifier written in `importer` (a virtual path), as the virtual path it names. */
export function joinVirtual(importer: string, specifier: string): string {
  return posix.normalize(posix.join(posix.dirname(importer), specifier.split('?')[0] ?? ''));
}

/** The candidates a relative import may resolve to, in the order a bundler tries them. */
export function resolutionCandidates(base: string): string[] {
  return [
    base,
    `${base}.ts`,
    `${base}.svelte`,
    `${base}.svelte.ts`,
    `${base}.js`,
    `${base}/index.ts`,
    base.replace(/\.js$/, '.ts'),
  ];
}

/** A relative specifier from one virtual path to another, with a leading `./` when it needs one. */
export function relativeSpecifier(from: string, to: string): string {
  const relative = posix.relative(posix.dirname(from), to);
  return relative.startsWith('.') ? relative : `./${relative}`;
}
