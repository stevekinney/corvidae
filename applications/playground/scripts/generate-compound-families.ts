/**
 * Generate the playground's compound-component relationships from component metadata.
 *
 * ```sh
 * bun scripts/generate-compound-families.ts           # write src/shell-app/compound-families.generated.ts
 * bun scripts/generate-compound-families.ts --check   # exit 1 when that file is stale
 * ```
 *
 * A compound root lists its parts in `compound.parts` of its `<name>.meta.json`, and a part with
 * no standalone use carries `composeOnly: true` (cinder, chat, editor and terminal alike). The
 * playground's browser code cannot read those files, so this writes the three relationships it
 * needs into one module: the families (root to parts), the parents (part to root), and the
 * compose-only parts its sidebar folds under their roots.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import * as prettier from 'prettier';

import {
  COMPONENT_PACKAGE_ROOTS,
  readPackageMeta,
} from '../../../components/cinder/scripts/lib/component-meta.ts';

export const COMPOUND_FAMILIES_MODULE = join(
  import.meta.dir,
  '..',
  'src',
  'shell-app',
  'compound-families.generated.ts',
);

/** The relationships, as plain data, in a stable order. */
export type CompoundRelationships = {
  families: Record<string, string[]>;
  parents: Record<string, string>;
  composeOnly: string[];
};

/** Read every package's component metadata into the relationships. Throws on unreadable files. */
export function readCompoundRelationships(): CompoundRelationships {
  const families: Record<string, string[]> = {};
  const parents: Record<string, string> = {};
  const composeOnly: string[] = [];
  const problems: string[] = [];
  const metadata = COMPONENT_PACKAGE_ROOTS.flatMap((root) => {
    const read = readPackageMeta(root);
    problems.push(...read.errors.map((error) => `${error.file}: ${error.reason}`));
    return read.metadata;
  }).toSorted((left, right) => (left.id < right.id ? -1 : 1));
  for (const meta of metadata) {
    if (meta.compound !== undefined) {
      families[meta.id] = meta.compound.parts;
      for (const part of meta.compound.parts) {
        if (Object.hasOwn(parents, part)) {
          problems.push(`${part} is a part of both ${parents[part]} and ${meta.id}`);
        }
        parents[part] = meta.id;
      }
    }
    if (meta.composeOnly === true) composeOnly.push(meta.id);
  }
  for (const part of composeOnly) {
    if (!Object.hasOwn(parents, part)) {
      problems.push(`${part} is composeOnly but no compound root lists it in compound.parts`);
    }
  }
  if (problems.length > 0) {
    throw new Error(
      `component metadata does not describe the compounds:\n  ${problems.join('\n  ')}`,
    );
  }
  return { families, parents, composeOnly };
}

/** The module text for the relationships, formatted as the repository formats TypeScript. */
export async function renderCompoundFamiliesModule(
  relationships: CompoundRelationships,
): Promise<string> {
  const text = `/**
 * Generated by \`bun scripts/generate-compound-families.ts\` from each component's \`<name>.meta.json\`
 * (\`compound.parts\` on a root, \`composeOnly\` on a part). Do not edit: change the metadata and
 * run the generator; \`--check\` fails when this file is stale.
 */

/** Compound roots and their parts, in display order. */
export const COMPOUND_COMPONENT_FAMILIES: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(relationships.families)};

/** Each compound part and its root. */
export const COMPOUND_COMPONENT_PARENTS: Readonly<Record<string, string>> = ${JSON.stringify(relationships.parents)};

/**
 * Compound parts with no standalone use. The sidebar lists them under their root, and they keep a
 * \`/c/<part>\` page.
 */
export const COMPOSE_ONLY_COMPONENTS: ReadonlySet<string> = new Set(${JSON.stringify(relationships.composeOnly)});
`;
  const options = await prettier.resolveConfig(COMPOUND_FAMILIES_MODULE);
  return prettier.format(text, { ...options, filepath: COMPOUND_FAMILIES_MODULE });
}

if (import.meta.main) {
  const text = await renderCompoundFamiliesModule(readCompoundRelationships());
  const current = existsSync(COMPOUND_FAMILIES_MODULE)
    ? readFileSync(COMPOUND_FAMILIES_MODULE, 'utf8')
    : undefined;
  if (process.argv.includes('--check')) {
    if (current !== text) {
      process.stderr.write(
        'src/shell-app/compound-families.generated.ts is stale: run `bun scripts/generate-compound-families.ts` in applications/playground.\n',
      );
      process.exitCode = 1;
    }
  } else if (current !== text) {
    writeFileSync(COMPOUND_FAMILIES_MODULE, text);
    process.stdout.write('generated src/shell-app/compound-families.generated.ts\n');
  }
}
